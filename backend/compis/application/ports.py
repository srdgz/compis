from datetime import date, datetime
from typing import Protocol

from compis.domain.entities import (
    Activity,
    Debt,
    Expense,
    FileRecord,
    Home,
    Roomie,
    ShoppingItem,
    ShoppingList,
    Task,
)


class RoomieRepository(Protocol):
    def add(self, roomie: Roomie, /) -> Roomie: ...
    def get(self, roomie_id: int, /) -> Roomie | None: ...
    def get_by_email(self, email: str) -> Roomie | None: ...
    def list_by_home(self, home_id: int) -> list[Roomie]: ...
    def save(self, roomie: Roomie, /) -> None: ...


class HomeRepository(Protocol):
    def add(self, home: Home, /) -> Home: ...
    def get(self, home_id: int, /) -> Home | None: ...
    def save(self, home: Home, /) -> None: ...


class TaskRepository(Protocol):
    def add(self, task: Task, /) -> Task: ...
    def get(self, task_id: int, /) -> Task | None: ...
    def list_by_roomie(self, roomie_id: int) -> list[Task]: ...
    def list_by_home(self, home_id: int) -> list[Task]: ...
    def save(self, task: Task, /) -> None: ...
    def delete(self, task_id: int, /) -> None: ...


class ShoppingRepository(Protocol):
    def add_list(self, shopping_list: ShoppingList) -> ShoppingList: ...
    def get_list(self, list_id: int) -> ShoppingList | None: ...
    def get_list_by_home(self, home_id: int) -> ShoppingList | None: ...
    def add_item(self, item: ShoppingItem) -> ShoppingItem: ...
    def get_item(self, item_id: int) -> ShoppingItem | None: ...
    def list_items(self, list_id: int, purchased: bool) -> list[ShoppingItem]: ...
    def save_item(self, item: ShoppingItem) -> None: ...
    def delete_item(self, item_id: int) -> None: ...


class ExpenseRepository(Protocol):
    def add(self, expense: Expense, /) -> Expense: ...
    def get(self, expense_id: int, /) -> Expense | None: ...
    def list_without_debts(self, roomie_id: int) -> list[Expense]: ...
    def save(self, expense: Expense, /) -> None: ...


class DebtRepository(Protocol):
    def add(self, debt: Debt, /) -> Debt: ...
    def get(self, debt_id: int, /) -> Debt | None: ...
    def list_for_roomie(self, roomie_id: int, pending_only: bool) -> list[Debt]: ...
    def has_pending(self, roomie_id: int) -> bool: ...
    def save(self, debt: Debt, /) -> None: ...


class FileRepository(Protocol):
    def add(self, file: FileRecord, /) -> FileRecord: ...
    def get(self, file_id: int, /) -> FileRecord | None: ...
    def list_by_home(self, home_id: int) -> list[FileRecord]: ...
    def delete(self, file_id: int, /) -> None: ...


class ActivityRepository(Protocol):
    def add(self, activity: Activity, /) -> Activity: ...
    def list_by_home(self, home_id: int, limit: int) -> list[Activity]: ...
    def list_since(self, since: datetime) -> list[Activity]: ...


class UnitOfWork(Protocol):
    @property
    def roomies(self) -> RoomieRepository: ...

    @property
    def homes(self) -> HomeRepository: ...

    @property
    def tasks(self) -> TaskRepository: ...

    @property
    def shopping(self) -> ShoppingRepository: ...

    @property
    def expenses(self) -> ExpenseRepository: ...

    @property
    def debts(self) -> DebtRepository: ...

    @property
    def files(self) -> FileRepository: ...

    @property
    def activities(self) -> ActivityRepository: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password_hash: str, password: str) -> bool: ...


class Clock(Protocol):
    def now(self) -> datetime: ...

    def today(self) -> date: ...


class Mailer(Protocol):
    def send(self, subject: str, html: str, recipients: list[str]) -> None: ...
